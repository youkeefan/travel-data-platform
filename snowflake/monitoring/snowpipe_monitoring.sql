
-- Travel Data Platform: Snowpipe Monitoring
-- Account Usage data may be delayed.

USE ROLE ACCOUNTADMIN;

-- 1. Recent ingestion history
SELECT
    PIPE_NAME,
    TABLE_NAME,
    FILE_NAME,
    STATUS,
    ROW_COUNT,
    ERROR_COUNT,
    FIRST_ERROR_MESSAGE,
    LAST_LOAD_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.COPY_HISTORY
WHERE TABLE_CATALOG_NAME = 'TRAVEL_DB'
  AND TABLE_SCHEMA_NAME = 'BRONZE'
  AND LAST_LOAD_TIME >= DATEADD('day', -1, CURRENT_TIMESTAMP())
ORDER BY LAST_LOAD_TIME DESC;

-- 2. Failed or partially loaded files
SELECT
    PIPE_NAME,
    TABLE_NAME,
    FILE_NAME,
    STATUS,
    ERROR_COUNT,
    FIRST_ERROR_MESSAGE,
    LAST_LOAD_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.COPY_HISTORY
WHERE TABLE_CATALOG_NAME = 'TRAVEL_DB'
  AND TABLE_SCHEMA_NAME = 'BRONZE'
  AND LAST_LOAD_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
  AND (
      STATUS NOT IN ('Loaded', 'LOADED')
      OR COALESCE(ERROR_COUNT, 0) > 0
  )
ORDER BY LAST_LOAD_TIME DESC;
