USE ROLE ACCOUNTADMIN;

CREATE SCHEMA IF NOT EXISTS TRAVEL_DB.MONITORING;

CREATE TABLE IF NOT EXISTS TRAVEL_DB.MONITORING.DBT_REFRESH_CONTROL (
    PIPELINE_NAME VARCHAR PRIMARY KEY,
    LAST_PROCESSED_LOAD_TIME TIMESTAMP_LTZ,
    LAST_SUCCESSFUL_REFRESH_AT TIMESTAMP_LTZ,
    LAST_RUN_AT TIMESTAMP_LTZ,
    LAST_RUN_STATUS VARCHAR,
    LAST_RUN_MESSAGE VARCHAR
);

MERGE INTO TRAVEL_DB.MONITORING.DBT_REFRESH_CONTROL AS target
USING (
    SELECT 'TRAVEL_DBT_PROD' AS PIPELINE_NAME
) AS source
ON target.PIPELINE_NAME = source.PIPELINE_NAME

WHEN NOT MATCHED THEN
    INSERT (
        PIPELINE_NAME,
        LAST_RUN_STATUS
    )
    VALUES (
        source.PIPELINE_NAME,
        'NOT_STARTED'
    );

--Grant control table permissions
USE ROLE ACCOUNTADMIN;

GRANT SELECT, UPDATE
ON TABLE TRAVEL_DB.MONITORING.DBT_REFRESH_CONTROL
TO ROLE TRAVEL_PROD_ROLE;


--Create a restricted ingestion history view
CREATE OR REPLACE SECURE VIEW
    TRAVEL_DB.MONITORING.BRONZE_INGESTION_HISTORY
AS
SELECT
    TABLE_NAME,
    FILE_NAME,
    PIPE_NAME,
    LAST_LOAD_TIME,
    ROW_COUNT,
    STATUS,
    ERROR_COUNT
FROM SNOWFLAKE.ACCOUNT_USAGE.COPY_HISTORY
WHERE TABLE_CATALOG_NAME = 'TRAVEL_DB'
  AND TABLE_SCHEMA_NAME = 'BRONZE';


GRANT SELECT
ON VIEW TRAVEL_DB.MONITORING.BRONZE_INGESTION_HISTORY
TO ROLE TRAVEL_PROD_ROLE;


--Create a persistent refresh detection view
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE VIEW
    TRAVEL_DB.MONITORING.DBT_REFRESH_STATUS
AS

WITH pending AS (
    SELECT
        COUNT(*) AS UNPROCESSED_FILE_COUNT,
        MAX(LAST_LOAD_TIME) AS LATEST_PENDING_LOAD_TIME
    FROM TRAVEL_DB.MONITORING.DBT_UNPROCESSED_FILES
)

SELECT
    c.PIPELINE_NAME,
    c.LAST_PROCESSED_LOAD_TIME,
    c.LAST_SUCCESSFUL_REFRESH_AT,
    c.LAST_RUN_STATUS,
    p.UNPROCESSED_FILE_COUNT,
    p.LATEST_PENDING_LOAD_TIME,

    CASE
        WHEN c.LAST_SUCCESSFUL_REFRESH_AT IS NULL
            THEN TRUE
        WHEN c.LAST_RUN_STATUS = 'FAILED'
            THEN TRUE
        WHEN p.UNPROCESSED_FILE_COUNT > 0
            THEN TRUE
        ELSE FALSE
    END AS REFRESH_REQUIRED

FROM TRAVEL_DB.MONITORING.DBT_REFRESH_CONTROL c
CROSS JOIN pending p
WHERE c.PIPELINE_NAME = 'TRAVEL_DBT_PROD';

GRANT SELECT
ON VIEW TRAVEL_DB.MONITORING.DBT_REFRESH_STATUS
TO ROLE TRAVEL_PROD_ROLE;

GRANT SELECT
ON VIEW TRAVEL_DB.MONITORING.DBT_REFRESH_STATUS
TO ROLE TRAVEL_PROD_ROLE;

--Create the processed files table
USE ROLE ACCOUNTADMIN;

CREATE TABLE IF NOT EXISTS
    TRAVEL_DB.MONITORING.DBT_PROCESSED_FILES (
        TABLE_NAME VARCHAR NOT NULL,
        FILE_NAME VARCHAR NOT NULL,
        LAST_LOAD_TIME TIMESTAMP_LTZ NOT NULL,
        PROCESSED_AT TIMESTAMP_LTZ
            DEFAULT CURRENT_TIMESTAMP(),

        PRIMARY KEY (
            TABLE_NAME,
            FILE_NAME,
            LAST_LOAD_TIME
        )
    );

GRANT SELECT, INSERT
ON TABLE TRAVEL_DB.MONITORING.DBT_PROCESSED_FILES
TO ROLE TRAVEL_PROD_ROLE;

--Upgrade the refresh detection view
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE VIEW
    TRAVEL_DB.MONITORING.DBT_UNPROCESSED_FILES
AS
SELECT DISTINCT
    h.TABLE_NAME,
    h.FILE_NAME,
    h.LAST_LOAD_TIME
FROM TRAVEL_DB.MONITORING.BRONZE_INGESTION_HISTORY h
WHERE UPPER(h.STATUS) IN ('LOADED', 'PARTIALLY LOADED')
  AND h.ROW_COUNT > 0
  AND NOT EXISTS (
      SELECT 1
      FROM TRAVEL_DB.MONITORING.DBT_PROCESSED_FILES p
      WHERE p.TABLE_NAME = h.TABLE_NAME
        AND p.FILE_NAME = h.FILE_NAME
        AND p.LAST_LOAD_TIME = h.LAST_LOAD_TIME
  );

GRANT SELECT
ON VIEW TRAVEL_DB.MONITORING.DBT_UNPROCESSED_FILES
TO ROLE TRAVEL_PROD_ROLE;