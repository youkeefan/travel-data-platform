USE ROLE ACCOUNTADMIN;

-- 1. Dedicated application role
CREATE ROLE IF NOT EXISTS TRAVEL_APP_ROLE
    COMMENT = 'Restricted execution role for Travel Intelligence Assistant';

GRANT ROLE TRAVEL_APP_ROLE TO ROLE SYSADMIN;

-- 2. Cortex AI access
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER
TO ROLE TRAVEL_APP_ROLE;

-- 3. Database and schema access
GRANT USAGE ON DATABASE TRAVEL_DEV_DB
TO ROLE TRAVEL_APP_ROLE;

GRANT USAGE ON SCHEMA TRAVEL_DEV_DB.GOLD
TO ROLE TRAVEL_APP_ROLE;

GRANT USAGE ON SCHEMA TRAVEL_DEV_DB.SEMANTIC
TO ROLE TRAVEL_APP_ROLE;

-- 4. Compute resources
GRANT USAGE ON WAREHOUSE COMPUTE_WH
TO ROLE TRAVEL_APP_ROLE;

GRANT USAGE ON COMPUTE POOL SYSTEM_COMPUTE_POOL_CPU
TO ROLE TRAVEL_APP_ROLE;

-- 5. Semantic view access
GRANT SELECT, REFERENCES ON SEMANTIC VIEW
TRAVEL_DEV_DB.SEMANTIC.COMMERCIAL_ANALYTICS
TO ROLE TRAVEL_APP_ROLE;

GRANT SELECT, REFERENCES ON SEMANTIC VIEW
TRAVEL_DEV_DB.SEMANTIC.CUSTOMER_ANALYTICS
TO ROLE TRAVEL_APP_ROLE;

GRANT SELECT, REFERENCES ON SEMANTIC VIEW
TRAVEL_DEV_DB.SEMANTIC.FINANCIAL_ANALYTICS
TO ROLE TRAVEL_APP_ROLE;

GRANT SELECT, REFERENCES ON SEMANTIC VIEW
TRAVEL_DEV_DB.SEMANTIC.LOYALTY_ANALYTICS
TO ROLE TRAVEL_APP_ROLE;

-- 6. Read-only access to underlying Gold marts
GRANT SELECT ON TABLE
TRAVEL_DEV_DB.GOLD.MART_COMMERCIAL_DAILY
TO ROLE TRAVEL_APP_ROLE;

GRANT SELECT ON TABLE
TRAVEL_DEV_DB.GOLD.MART_CUSTOMER_360
TO ROLE TRAVEL_APP_ROLE;

GRANT SELECT ON TABLE
TRAVEL_DEV_DB.GOLD.MART_FINANCIAL_DAILY
TO ROLE TRAVEL_APP_ROLE;

GRANT SELECT ON TABLE
TRAVEL_DEV_DB.GOLD.MART_LOYALTY_MONTHLY
TO ROLE TRAVEL_APP_ROLE;

-- 7. Dedicated application schema
CREATE SCHEMA IF NOT EXISTS TRAVEL_DEV_DB.APPS;

GRANT USAGE ON SCHEMA TRAVEL_DEV_DB.APPS
TO ROLE TRAVEL_APP_ROLE;

GRANT CREATE STREAMLIT ON SCHEMA TRAVEL_DEV_DB.APPS
TO ROLE TRAVEL_APP_ROLE;