
CREATE OR REPLACE SEMANTIC VIEW SEMANTIC.CUSTOMER_ANALYTICS

TABLES (
    CUSTOMER AS GOLD.MART_CUSTOMER_360
        PRIMARY KEY (CUSTOMER_KEY)
        COMMENT = 'Customer-level lifetime commercial and loyalty activity, including customers without purchases.'
)

FACTS (
    CUSTOMER.BOOKING_COUNT AS TOTAL_BOOKINGS,
    CUSTOMER.BOOKING_ITEM_COUNT AS TOTAL_BOOKING_ITEMS,
    CUSTOMER.SALES_AMOUNT AS LIFETIME_GROSS_SALES_AUD,
    CUSTOMER.MARGIN_AMOUNT AS LIFETIME_GROSS_MARGIN_AUD,
    CUSTOMER.DISCOUNT_AMOUNT AS LIFETIME_DISCOUNT_AUD,
    CUSTOMER.ROOM_NIGHT_COUNT AS TOTAL_ROOM_NIGHTS,
    CUSTOMER.TRAVELLER_COUNT AS TOTAL_TRAVELLERS,

    CUSTOMER.POINTS_EARNED AS TOTAL_POINTS_EARNED,
    CUSTOMER.POINTS_REDEEMED AS TOTAL_POINTS_REDEEMED,
    CUSTOMER.POINTS_EXPIRED AS TOTAL_POINTS_EXPIRED,
    CUSTOMER.POINTS_ADJUSTED AS TOTAL_POINTS_ADJUSTED,
    CUSTOMER.POINTS_REVERSED AS TOTAL_POINTS_REVERSED,
    CUSTOMER.POINTS_MOVEMENT AS NET_POINTS_MOVEMENT,
    CUSTOMER.LOYALTY_EVENT_COUNT AS TOTAL_LOYALTY_EVENTS,

    CUSTOMER.RECENCY AS RECENCY_DAYS,
    CUSTOMER.TENURE AS TENURE_DAYS
)

DIMENSIONS (
    CUSTOMER.CUSTOMER_KEY AS CUSTOMER_KEY,
    CUSTOMER.AGE_BAND AS AGE_BAND,
    CUSTOMER.COUNTRY_CODE AS COUNTRY_CODE,
    CUSTOMER.TIER_NAME AS TIER_NAME,
    CUSTOMER.CUSTOMER_STATUS AS CUSTOMER_STATUS,
    CUSTOMER.CUSTOMER_SINCE AS CUSTOMER_SINCE,
    CUSTOMER.TENURE_BAND AS TENURE_BAND,

    CUSTOMER.FIRST_PURCHASE_DATE AS FIRST_PURCHASE_DATE,
    CUSTOMER.LAST_PURCHASE_DATE AS LAST_PURCHASE_DATE,
    CUSTOMER.LAST_LOYALTY_ACTIVITY_DATE AS LAST_LOYALTY_ACTIVITY_DATE,
    CUSTOMER.AS_OF_DATE AS AS_OF_DATE,

    CUSTOMER.PURCHASE_SEGMENT AS PURCHASE_SEGMENT,
    CUSTOMER.HAS_PURCHASED AS HAS_PURCHASED,
    CUSTOMER.IS_REPEAT_CUSTOMER AS IS_REPEAT_CUSTOMER,
    CUSTOMER.HAS_LOYALTY_ACTIVITY AS HAS_LOYALTY_ACTIVITY
)

METRICS (
    CUSTOMER.M_TOTAL_CUSTOMERS AS
        COUNT(DISTINCT CUSTOMER.CUSTOMER_KEY)
        WITH SYNONYMS = ('unique customers', 'customer count', 'total customers'),

    CUSTOMER.M_PURCHASING_CUSTOMERS AS
        COUNT(DISTINCT CASE
            WHEN CUSTOMER.HAS_PURCHASED
            THEN CUSTOMER.CUSTOMER_KEY
        END),

    CUSTOMER.M_REPEAT_CUSTOMERS AS
        COUNT(DISTINCT CASE
            WHEN CUSTOMER.IS_REPEAT_CUSTOMER
            THEN CUSTOMER.CUSTOMER_KEY
        END),

    CUSTOMER.M_LOYALTY_ACTIVE_CUSTOMERS AS
        COUNT(DISTINCT CASE
            WHEN CUSTOMER.HAS_LOYALTY_ACTIVITY
            THEN CUSTOMER.CUSTOMER_KEY
        END),

    CUSTOMER.M_TOTAL_BOOKINGS AS
        SUM(CUSTOMER.BOOKING_COUNT),

    CUSTOMER.M_TOTAL_BOOKING_ITEMS AS
        SUM(CUSTOMER.BOOKING_ITEM_COUNT),

    CUSTOMER.M_TOTAL_SALES AS
        SUM(CUSTOMER.SALES_AMOUNT)
        WITH SYNONYMS = ('lifetime sales', 'customer spend', 'gross sales')
        COMMENT = 'Total recorded lifetime gross sales in AUD.',

    CUSTOMER.M_TOTAL_MARGIN AS
        SUM(CUSTOMER.MARGIN_AMOUNT)
        WITH SYNONYMS = ('gross margin', 'lifetime margin'),

    CUSTOMER.M_TOTAL_DISCOUNT AS
        SUM(CUSTOMER.DISCOUNT_AMOUNT),

    CUSTOMER.M_TOTAL_ROOM_NIGHTS AS
        SUM(CUSTOMER.ROOM_NIGHT_COUNT),

    CUSTOMER.M_TOTAL_TRAVELLERS AS
        SUM(CUSTOMER.TRAVELLER_COUNT),

    CUSTOMER.M_TOTAL_POINTS_EARNED AS
        SUM(CUSTOMER.POINTS_EARNED),

    CUSTOMER.M_TOTAL_POINTS_REDEEMED AS
        SUM(CUSTOMER.POINTS_REDEEMED)
        WITH SYNONYMS = ('points burned', 'points spent'),

    CUSTOMER.M_TOTAL_POINTS_EXPIRED AS
        SUM(CUSTOMER.POINTS_EXPIRED),

    CUSTOMER.M_TOTAL_POINTS_ADJUSTED AS
        SUM(CUSTOMER.POINTS_ADJUSTED),

    CUSTOMER.M_TOTAL_POINTS_REVERSED AS
        SUM(CUSTOMER.POINTS_REVERSED),

    CUSTOMER.M_NET_POINTS_MOVEMENT AS
        SUM(CUSTOMER.POINTS_MOVEMENT)
        COMMENT = 'Net recorded points movement, not necessarily the outstanding points balance.',

    CUSTOMER.M_TOTAL_LOYALTY_EVENTS AS
        SUM(CUSTOMER.LOYALTY_EVENT_COUNT),

    CUSTOMER.M_GROSS_MARGIN_RATE AS
        SUM(CUSTOMER.MARGIN_AMOUNT)
        / NULLIF(SUM(CUSTOMER.SALES_AMOUNT), 0)
        COMMENT = 'Weighted gross margin rate expressed as a decimal.',

    CUSTOMER.M_AVERAGE_BOOKING_VALUE AS
        SUM(CUSTOMER.SALES_AMOUNT)
        / NULLIF(SUM(CUSTOMER.BOOKING_COUNT), 0)
        WITH SYNONYMS = ('average booking value', 'ABV'),

    CUSTOMER.M_AVERAGE_CUSTOMER_SPEND AS
        SUM(CUSTOMER.SALES_AMOUNT)
        / NULLIF(
            COUNT(DISTINCT CUSTOMER.CUSTOMER_KEY), 0
        )
        COMMENT = 'Average lifetime spend across all customers, including non-purchasers.',

    CUSTOMER.M_REPEAT_PURCHASE_RATE AS
        COUNT(DISTINCT CASE
            WHEN CUSTOMER.IS_REPEAT_CUSTOMER
            THEN CUSTOMER.CUSTOMER_KEY
        END)
        / NULLIF(
            COUNT(DISTINCT CASE
                WHEN CUSTOMER.HAS_PURCHASED
                THEN CUSTOMER.CUSTOMER_KEY
            END), 0
        )
        COMMENT = 'Repeat customers divided by purchasing customers, expressed as a decimal.',

    CUSTOMER.M_PURCHASE_CONVERSION_RATE AS
        COUNT(DISTINCT CASE
            WHEN CUSTOMER.HAS_PURCHASED
            THEN CUSTOMER.CUSTOMER_KEY
        END)
        / NULLIF(
            COUNT(DISTINCT CUSTOMER.CUSTOMER_KEY), 0
        )
        COMMENT = 'Proportion of customers with at least one recorded purchase.',

    CUSTOMER.M_AVERAGE_RECENCY_DAYS AS
        AVG(CUSTOMER.RECENCY)
        COMMENT = 'Average days since last purchase among customers with a recorded purchase.',

    CUSTOMER.M_AVERAGE_TENURE_DAYS AS
        AVG(CUSTOMER.TENURE)
)

COMMENT = 'Business semantic layer for customer lifetime spending, purchasing behaviour, membership segmentation and loyalty engagement.';
