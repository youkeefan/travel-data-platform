
CREATE OR REPLACE SEMANTIC VIEW SEMANTIC.FINANCIAL_ANALYTICS

TABLES (
    FINANCIAL AS GOLD.MART_FINANCIAL_DAILY
        PRIMARY KEY (FINANCIAL_DAILY_KEY)
        COMMENT = 'Daily payment and refund activity by transaction date and currency. Monetary amounts are in their original currencies.'
)

FACTS (
    FINANCIAL.PAYMENT_COUNT AS TOTAL_PAYMENT_COUNT,
    FINANCIAL.SUCCESSFUL_PAYMENTS AS SUCCESSFUL_PAYMENT_COUNT,
    FINANCIAL.FAILED_PAYMENTS AS FAILED_PAYMENT_COUNT,
    FINANCIAL.PENDING_PAYMENTS AS PENDING_PAYMENT_COUNT,

    FINANCIAL.PAYMENT_AMOUNT AS TOTAL_PAYMENT_AMOUNT,
    FINANCIAL.SUCCESSFUL_AMOUNT AS SUCCESSFUL_PAYMENT_AMOUNT,

    FINANCIAL.REFUND_COUNT AS TOTAL_REFUND_COUNT,
    FINANCIAL.COMPLETED_REFUNDS AS COMPLETED_REFUND_COUNT,
    FINANCIAL.FAILED_REFUNDS AS FAILED_REFUND_COUNT,
    FINANCIAL.PENDING_REFUNDS AS PENDING_REFUND_COUNT,

    FINANCIAL.VALIDATED_REFUNDS AS VALIDATED_COMPLETED_REFUND_COUNT,

    FINANCIAL.REFUND_AMOUNT AS TOTAL_REFUND_AMOUNT,
    FINANCIAL.COMPLETED_REFUND_VALUE AS COMPLETED_REFUND_AMOUNT,
    FINANCIAL.VALIDATED_REFUND_VALUE AS VALIDATED_COMPLETED_REFUND_AMOUNT,

    FINANCIAL.CASH_MOVEMENT AS NET_CASH_MOVEMENT
)

DIMENSIONS (
    FINANCIAL.TRANSACTION_DATE AS TRANSACTION_DATE,
    FINANCIAL.CALENDAR_YEAR AS CALENDAR_YEAR,
    FINANCIAL.CALENDAR_QUARTER AS CALENDAR_QUARTER,
    FINANCIAL.MONTH_NUMBER AS MONTH_NUMBER,
    FINANCIAL.YEAR_MONTH AS YEAR_MONTH,
    FINANCIAL.FINANCIAL_YEAR AS FINANCIAL_YEAR,
    FINANCIAL.FINANCIAL_QUARTER AS FINANCIAL_QUARTER,
    FINANCIAL.CURRENCY_CODE AS CURRENCY_CODE
)

METRICS (
    FINANCIAL.M_TOTAL_PAYMENTS AS
        SUM(FINANCIAL.PAYMENT_COUNT),

    FINANCIAL.M_SUCCESSFUL_PAYMENT_COUNT AS
        SUM(FINANCIAL.SUCCESSFUL_PAYMENTS),

    FINANCIAL.M_FAILED_PAYMENT_COUNT AS
        SUM(FINANCIAL.FAILED_PAYMENTS),

    FINANCIAL.M_PENDING_PAYMENT_COUNT AS
        SUM(FINANCIAL.PENDING_PAYMENTS),

    FINANCIAL.M_TOTAL_PAYMENT_AMOUNT AS
        SUM(FINANCIAL.PAYMENT_AMOUNT)
        COMMENT = 'Original currency amount. Always filter or group by currency.',

    FINANCIAL.M_SUCCESSFUL_PAYMENT_AMOUNT AS
        SUM(FINANCIAL.SUCCESSFUL_AMOUNT)
        COMMENT = 'Successful payment amount in original currency. Always filter or group by currency.',

    FINANCIAL.M_TOTAL_REFUNDS AS
        SUM(FINANCIAL.REFUND_COUNT),

    FINANCIAL.M_COMPLETED_REFUND_COUNT AS
        SUM(FINANCIAL.COMPLETED_REFUNDS),

    FINANCIAL.M_FAILED_REFUND_COUNT AS
        SUM(FINANCIAL.FAILED_REFUNDS),

    FINANCIAL.M_PENDING_REFUND_COUNT AS
        SUM(FINANCIAL.PENDING_REFUNDS),

    FINANCIAL.M_VALIDATED_REFUND_COUNT AS
        SUM(FINANCIAL.VALIDATED_REFUNDS),

    FINANCIAL.M_TOTAL_REFUND_AMOUNT AS
        SUM(FINANCIAL.REFUND_AMOUNT)
        COMMENT = 'Original currency amount. Always filter or group by currency.',

    FINANCIAL.M_COMPLETED_REFUND_AMOUNT AS
        SUM(FINANCIAL.COMPLETED_REFUND_VALUE)
        COMMENT = 'Original currency amount. Always filter or group by currency.',

    FINANCIAL.M_VALIDATED_REFUND_AMOUNT AS
        SUM(FINANCIAL.VALIDATED_REFUND_VALUE)
        COMMENT = 'Validated completed refunds in original currency. Always filter or group by currency.',

    FINANCIAL.M_NET_CASH_MOVEMENT AS
        SUM(FINANCIAL.CASH_MOVEMENT)
        WITH SYNONYMS = ('net cash flow', 'net payments')
        COMMENT = 'Successful payments minus validated completed refunds. Always filter or group by currency.',

    FINANCIAL.M_PAYMENT_SUCCESS_RATE AS
        SUM(FINANCIAL.SUCCESSFUL_PAYMENTS)
        / NULLIF(SUM(FINANCIAL.PAYMENT_COUNT), 0)
        COMMENT = 'Weighted payment success rate expressed as a decimal.',

    FINANCIAL.M_PAYMENT_FAILURE_RATE AS
        SUM(FINANCIAL.FAILED_PAYMENTS)
        / NULLIF(SUM(FINANCIAL.PAYMENT_COUNT), 0)
        COMMENT = 'Failed payments divided by total payment attempts.',

    FINANCIAL.M_REFUND_TO_PAYMENT_RATIO AS
        SUM(FINANCIAL.VALIDATED_REFUND_VALUE)
        / NULLIF(SUM(FINANCIAL.SUCCESSFUL_AMOUNT), 0)
        COMMENT = 'Validated completed refund amount divided by successful payment amount. Always filter or group by currency.',

    FINANCIAL.M_AVERAGE_SUCCESSFUL_PAYMENT AS
        SUM(FINANCIAL.SUCCESSFUL_AMOUNT)
        / NULLIF(SUM(FINANCIAL.SUCCESSFUL_PAYMENTS), 0)
        COMMENT = 'Average successful payment amount. Always filter or group by currency.'
)

COMMENT = 'Business semantic layer for payment performance, refund activity and net cash movement. Monetary metrics must not aggregate across currencies without conversion.';
