WITH refund_summary AS (

    SELECT
        PAYMENT_KEY,
        CURRENCY_CODE,
        COUNT(*) AS COMPLETED_REFUND_COUNT,
        SUM(REFUND_AMOUNT) AS TOTAL_COMPLETED_REFUNDS

    FROM {{ ref('fact_refunds') }}

    WHERE IS_COMPLETED_REFUND = TRUE
        AND IS_VALID_REFUND_AMOUNT = TRUE
        AND IS_BOOKING_CONSISTENT = TRUE
        AND IS_CURRENCY_CONSISTENT = TRUE
        AND IS_SUCCESSFUL_PAYMENT = TRUE

    GROUP BY 1, 2

)

SELECT
    p.PAYMENT_ID,
    p.BOOKING_ID,
    p.CURRENCY_CODE,
    p.PAYMENT_AMOUNT,

    r.COMPLETED_REFUND_COUNT,
    r.TOTAL_COMPLETED_REFUNDS,

    r.TOTAL_COMPLETED_REFUNDS - p.PAYMENT_AMOUNT
        AS OVER_REFUND_AMOUNT

FROM refund_summary r

INNER JOIN {{ ref('fact_payments') }} p
    ON r.PAYMENT_KEY = p.PAYMENT_KEY
    AND r.CURRENCY_CODE = p.CURRENCY_CODE

WHERE r.TOTAL_COMPLETED_REFUNDS > p.PAYMENT_AMOUNT