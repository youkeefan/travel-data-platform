WITH fact AS (

    SELECT
        TRANSACTION_DATE_KEY,
        PRODUCT_KEY,

        COUNT(*) AS BOOKING_ITEM_COUNT,

        SUM(GROSS_SALES_AUD) AS GROSS_SALES_AUD,
        SUM(GROSS_MARGIN_AUD) AS GROSS_MARGIN_AUD,
        SUM(DISCOUNT_AUD) AS DISCOUNT_AUD,
        SUM(REFUND_AUD) AS REFUND_AUD,
        SUM(ROOM_NIGHTS) AS ROOM_NIGHTS,
        SUM(TRAVELLER_COUNT) AS TRAVELLER_COUNT

    FROM {{ ref('fact_booking_items') }}

    WHERE GROSS_SALES_AUD > 0

    GROUP BY 1, 2

),

mart AS (

    SELECT *
    FROM {{ ref('mart_commercial_daily') }}

)

SELECT
    COALESCE(f.TRANSACTION_DATE_KEY, m.TRANSACTION_DATE_KEY)
        AS TRANSACTION_DATE_KEY,

    COALESCE(f.PRODUCT_KEY, m.PRODUCT_KEY)
        AS PRODUCT_KEY,

    f.GROSS_SALES_AUD AS FACT_GROSS_SALES,
    m.GROSS_SALES_AUD AS MART_GROSS_SALES,

    f.GROSS_MARGIN_AUD AS FACT_GROSS_MARGIN,
    m.GROSS_MARGIN_AUD AS MART_GROSS_MARGIN

FROM fact f

FULL OUTER JOIN mart m
    ON f.TRANSACTION_DATE_KEY = m.TRANSACTION_DATE_KEY
    AND f.PRODUCT_KEY = m.PRODUCT_KEY

WHERE f.TRANSACTION_DATE_KEY IS NULL
   OR m.TRANSACTION_DATE_KEY IS NULL
   OR f.BOOKING_ITEM_COUNT IS DISTINCT FROM m.BOOKING_ITEM_COUNT
   OR f.GROSS_SALES_AUD IS DISTINCT FROM m.GROSS_SALES_AUD
   OR f.GROSS_MARGIN_AUD IS DISTINCT FROM m.GROSS_MARGIN_AUD
   OR f.DISCOUNT_AUD IS DISTINCT FROM m.DISCOUNT_AUD
   OR f.REFUND_AUD IS DISTINCT FROM m.REFUND_AUD
   OR f.ROOM_NIGHTS IS DISTINCT FROM m.ROOM_NIGHTS
   OR f.TRAVELLER_COUNT IS DISTINCT FROM m.TRAVELLER_COUNT