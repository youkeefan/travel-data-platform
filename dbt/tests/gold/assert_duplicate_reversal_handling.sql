WITH reversal_summary AS (

    SELECT
        RELATED_LEDGER_ID,

        COUNT(*) AS REVERSAL_COUNT,

        COUNT_IF(IS_VALID_POINTS_MOVEMENT)
            AS VALID_REVERSAL_COUNT,

        COUNT_IF(IS_DUPLICATE_REVERSAL)
            AS DUPLICATE_REVERSAL_COUNT,

        COUNT_IF(
            IS_DUPLICATE_REVERSAL
            AND VALIDATED_POINTS_MOVEMENT <> 0
        ) AS INVALID_DUPLICATE_MOVEMENT

    FROM {{ ref('fact_points_ledger') }}

    WHERE EVENT_TYPE = 'REVERSAL'
        AND IS_VALID_REVERSAL_REFERENCE = TRUE
        AND IS_VALID_POINTS_AMOUNT = TRUE

    GROUP BY 1

)

SELECT *
FROM reversal_summary

WHERE VALID_REVERSAL_COUNT <> 1
   OR DUPLICATE_REVERSAL_COUNT <> REVERSAL_COUNT - 1
   OR INVALID_DUPLICATE_MOVEMENT > 0