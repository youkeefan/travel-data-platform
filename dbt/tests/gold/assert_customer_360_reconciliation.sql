WITH customers AS (

    SELECT CUSTOMER_KEY
    FROM {{ ref('dim_customer') }}
    WHERE CUSTOMER_KEY <> 'UNKNOWN'

),

commercial AS (

    SELECT
        CUSTOMER_KEY,
        COUNT(DISTINCT BOOKING_ID) AS TOTAL_BOOKINGS,
        COUNT(*) AS TOTAL_BOOKING_ITEMS,
        SUM(GROSS_SALES_AUD) AS LIFETIME_GROSS_SALES_AUD,
        SUM(GROSS_MARGIN_AUD) AS LIFETIME_GROSS_MARGIN_AUD,
        SUM(DISCOUNT_AUD) AS LIFETIME_DISCOUNT_AUD

    FROM {{ ref('fact_booking_items') }}

    WHERE GROSS_SALES_AUD > 0
        AND HAS_VALID_CUSTOMER = TRUE

    GROUP BY 1

),

loyalty AS (

    SELECT
        CUSTOMER_KEY,
        COUNT(*) AS TOTAL_LOYALTY_EVENTS,
        SUM(CURRENT_POINTS_MOVEMENT) AS NET_POINTS_MOVEMENT

    FROM {{ ref('fact_points_ledger') }}

    WHERE IS_VALID_POINTS_MOVEMENT = TRUE
        AND IS_FUTURE_EVENT = FALSE
        AND HAS_VALID_DATE_KEY = TRUE
        AND HAS_VALID_CUSTOMER = TRUE

    GROUP BY 1

),

expected AS (

    SELECT
        c.CUSTOMER_KEY,

        COALESCE(a.TOTAL_BOOKINGS, 0)
            AS TOTAL_BOOKINGS,

        COALESCE(a.TOTAL_BOOKING_ITEMS, 0)
            AS TOTAL_BOOKING_ITEMS,

        COALESCE(a.LIFETIME_GROSS_SALES_AUD, 0)
            AS LIFETIME_GROSS_SALES_AUD,

        COALESCE(a.LIFETIME_GROSS_MARGIN_AUD, 0)
            AS LIFETIME_GROSS_MARGIN_AUD,

        COALESCE(a.LIFETIME_DISCOUNT_AUD, 0)
            AS LIFETIME_DISCOUNT_AUD,

        COALESCE(l.TOTAL_LOYALTY_EVENTS, 0)
            AS TOTAL_LOYALTY_EVENTS,

        COALESCE(l.NET_POINTS_MOVEMENT, 0)
            AS NET_POINTS_MOVEMENT

    FROM customers c

    LEFT JOIN commercial a
        ON c.CUSTOMER_KEY = a.CUSTOMER_KEY

    LEFT JOIN loyalty l
        ON c.CUSTOMER_KEY = l.CUSTOMER_KEY

),

mart AS (

    SELECT *
    FROM {{ ref('mart_customer_360') }}

)

SELECT
    COALESCE(e.CUSTOMER_KEY, m.CUSTOMER_KEY)
        AS CUSTOMER_KEY,

    e.TOTAL_BOOKINGS AS EXPECTED_BOOKINGS,
    m.TOTAL_BOOKINGS AS ACTUAL_BOOKINGS,

    e.LIFETIME_GROSS_SALES_AUD AS EXPECTED_GROSS_SALES,
    m.LIFETIME_GROSS_SALES_AUD AS ACTUAL_GROSS_SALES,

    e.NET_POINTS_MOVEMENT AS EXPECTED_POINTS_MOVEMENT,
    m.NET_POINTS_MOVEMENT AS ACTUAL_POINTS_MOVEMENT

FROM expected e

FULL OUTER JOIN mart m
    ON e.CUSTOMER_KEY = m.CUSTOMER_KEY

WHERE e.CUSTOMER_KEY IS NULL
   OR m.CUSTOMER_KEY IS NULL
   OR e.TOTAL_BOOKINGS IS DISTINCT FROM m.TOTAL_BOOKINGS
   OR e.TOTAL_BOOKING_ITEMS IS DISTINCT FROM m.TOTAL_BOOKING_ITEMS
   OR e.LIFETIME_GROSS_SALES_AUD IS DISTINCT FROM m.LIFETIME_GROSS_SALES_AUD
   OR e.LIFETIME_GROSS_MARGIN_AUD IS DISTINCT FROM m.LIFETIME_GROSS_MARGIN_AUD
   OR e.LIFETIME_DISCOUNT_AUD IS DISTINCT FROM m.LIFETIME_DISCOUNT_AUD
   OR e.TOTAL_LOYALTY_EVENTS IS DISTINCT FROM m.TOTAL_LOYALTY_EVENTS
   OR e.NET_POINTS_MOVEMENT IS DISTINCT FROM m.NET_POINTS_MOVEMENT