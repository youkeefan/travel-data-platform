WITH monthly AS (

    SELECT
        DATE_TRUNC('MONTH', EVENT_DATE)::DATE
            AS MONTH_START_DATE,

        CUSTOMER_KEY,

        COUNT(*) AS LOYALTY_EVENT_COUNT,

        SUM(POINTS_EARNED) AS POINTS_EARNED,
        SUM(POINTS_REDEEMED) AS POINTS_REDEEMED,
        SUM(POINTS_EXPIRED) AS POINTS_EXPIRED,
        SUM(POINTS_ADJUSTED) AS POINTS_ADJUSTED,
        SUM(POINTS_REVERSED) AS POINTS_REVERSED,

        SUM(CURRENT_POINTS_MOVEMENT)
            AS NET_POINTS_MOVEMENT

    FROM {{ ref('fact_points_ledger') }}

    WHERE IS_VALID_POINTS_MOVEMENT = TRUE
        AND IS_FUTURE_EVENT = FALSE
        AND HAS_VALID_DATE_KEY = TRUE
        AND HAS_VALID_CUSTOMER = TRUE

    GROUP BY 1, 2

),

expected AS (

    SELECT
        *,

        SUM(NET_POINTS_MOVEMENT) OVER (
            PARTITION BY CUSTOMER_KEY
            ORDER BY MONTH_START_DATE
            ROWS BETWEEN UNBOUNDED PRECEDING
                AND CURRENT ROW
        ) AS CUMULATIVE_POINTS_MOVEMENT

    FROM monthly

),

mart AS (

    SELECT *
    FROM {{ ref('mart_loyalty_monthly') }}

)

SELECT
    COALESCE(e.MONTH_START_DATE, m.MONTH_START_DATE)
        AS MONTH_START_DATE,

    COALESCE(e.CUSTOMER_KEY, m.CUSTOMER_KEY)
        AS CUSTOMER_KEY,

    e.NET_POINTS_MOVEMENT AS EXPECTED_NET_MOVEMENT,
    m.NET_POINTS_MOVEMENT AS ACTUAL_NET_MOVEMENT,

    e.CUMULATIVE_POINTS_MOVEMENT AS EXPECTED_CUMULATIVE,
    m.CUMULATIVE_POINTS_MOVEMENT AS ACTUAL_CUMULATIVE

FROM expected e

FULL OUTER JOIN mart m
    ON e.MONTH_START_DATE = m.MONTH_START_DATE
    AND e.CUSTOMER_KEY = m.CUSTOMER_KEY

WHERE e.CUSTOMER_KEY IS NULL
   OR m.CUSTOMER_KEY IS NULL
   OR e.LOYALTY_EVENT_COUNT IS DISTINCT FROM m.LOYALTY_EVENT_COUNT
   OR e.POINTS_EARNED IS DISTINCT FROM m.POINTS_EARNED
   OR e.POINTS_REDEEMED IS DISTINCT FROM m.POINTS_REDEEMED
   OR e.POINTS_EXPIRED IS DISTINCT FROM m.POINTS_EXPIRED
   OR e.POINTS_ADJUSTED IS DISTINCT FROM m.POINTS_ADJUSTED
   OR e.POINTS_REVERSED IS DISTINCT FROM m.POINTS_REVERSED
   OR e.NET_POINTS_MOVEMENT IS DISTINCT FROM m.NET_POINTS_MOVEMENT
   OR e.CUMULATIVE_POINTS_MOVEMENT IS DISTINCT FROM m.CUMULATIVE_POINTS_MOVEMENT