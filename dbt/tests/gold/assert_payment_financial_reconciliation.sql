WITH silver AS (

    SELECT
        CURRENCY_CODE,
        UPPER(TRIM(PAYMENT_STATUS)) AS PAYMENT_STATUS,
        COUNT(*) AS PAYMENT_COUNT,
        SUM(PAYMENT_AMOUNT) AS TOTAL_PAYMENT_AMOUNT

    FROM {{ ref('stg_payments') }}

    GROUP BY 1, 2

),

gold AS (

    SELECT
        CURRENCY_CODE,
        PAYMENT_STATUS,
        COUNT(*) AS PAYMENT_COUNT,
        SUM(PAYMENT_AMOUNT) AS TOTAL_PAYMENT_AMOUNT

    FROM {{ ref('fact_payments') }}

    GROUP BY 1, 2

)

SELECT
    COALESCE(s.CURRENCY_CODE, g.CURRENCY_CODE)
        AS CURRENCY_CODE,

    COALESCE(s.PAYMENT_STATUS, g.PAYMENT_STATUS)
        AS PAYMENT_STATUS,

    s.PAYMENT_COUNT AS SILVER_PAYMENT_COUNT,
    g.PAYMENT_COUNT AS GOLD_PAYMENT_COUNT,

    s.TOTAL_PAYMENT_AMOUNT AS SILVER_PAYMENT_AMOUNT,
    g.TOTAL_PAYMENT_AMOUNT AS GOLD_PAYMENT_AMOUNT,

    g.PAYMENT_COUNT - s.PAYMENT_COUNT
        AS COUNT_VARIANCE,

    g.TOTAL_PAYMENT_AMOUNT - s.TOTAL_PAYMENT_AMOUNT
        AS AMOUNT_VARIANCE

FROM silver s

FULL OUTER JOIN gold g
    ON s.CURRENCY_CODE = g.CURRENCY_CODE
    AND s.PAYMENT_STATUS = g.PAYMENT_STATUS

WHERE s.PAYMENT_COUNT IS DISTINCT FROM g.PAYMENT_COUNT
   OR s.TOTAL_PAYMENT_AMOUNT
        IS DISTINCT FROM g.TOTAL_PAYMENT_AMOUNT