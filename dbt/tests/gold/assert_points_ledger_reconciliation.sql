WITH silver AS (

    SELECT
        EVENT_TYPE,
        ADJUSTMENT_DIRECTION,
        COUNT(*) AS EVENT_COUNT,
        SUM(POINTS_AMOUNT) AS TOTAL_POINTS

    FROM {{ ref('stg_points_ledger') }}

    GROUP BY 1, 2

),

gold AS (

    SELECT
        EVENT_TYPE,
        ADJUSTMENT_DIRECTION,
        COUNT(*) AS EVENT_COUNT,
        SUM(POINTS_AMOUNT) AS TOTAL_POINTS

    FROM {{ ref('fact_points_ledger') }}

    GROUP BY 1, 2

)

SELECT
    COALESCE(s.EVENT_TYPE, g.EVENT_TYPE)
        AS EVENT_TYPE,

    COALESCE(s.ADJUSTMENT_DIRECTION, g.ADJUSTMENT_DIRECTION)
        AS ADJUSTMENT_DIRECTION,

    s.EVENT_COUNT AS SILVER_EVENT_COUNT,
    g.EVENT_COUNT AS GOLD_EVENT_COUNT,

    s.TOTAL_POINTS AS SILVER_POINTS,
    g.TOTAL_POINTS AS GOLD_POINTS,

    g.EVENT_COUNT - s.EVENT_COUNT
        AS COUNT_VARIANCE,

    g.TOTAL_POINTS - s.TOTAL_POINTS
        AS POINTS_VARIANCE

FROM silver s

FULL OUTER JOIN gold g
    ON s.EVENT_TYPE IS NOT DISTINCT FROM g.EVENT_TYPE
    AND s.ADJUSTMENT_DIRECTION
        IS NOT DISTINCT FROM g.ADJUSTMENT_DIRECTION

WHERE s.EVENT_COUNT IS DISTINCT FROM g.EVENT_COUNT
   OR s.TOTAL_POINTS IS DISTINCT FROM g.TOTAL_POINTS