WITH payments AS (

    SELECT
        PAYMENT_DATE_KEY AS DATE_KEY,
        CURRENCY_CODE,

        COUNT(*) AS TOTAL_PAYMENT_COUNT,

        SUM(CASE WHEN PAYMENT_STATUS = 'SUCCESSFUL'
            THEN 1 ELSE 0 END)
            AS SUCCESSFUL_PAYMENT_COUNT,

        SUM(CASE WHEN PAYMENT_STATUS = 'FAILED'
            THEN 1 ELSE 0 END)
            AS FAILED_PAYMENT_COUNT,

        SUM(CASE WHEN PAYMENT_STATUS = 'PENDING'
            THEN 1 ELSE 0 END)
            AS PENDING_PAYMENT_COUNT,

        SUM(PAYMENT_AMOUNT)
            AS TOTAL_PAYMENT_AMOUNT,

        SUM(SUCCESSFUL_PAYMENT_AMOUNT)
            AS SUCCESSFUL_PAYMENT_AMOUNT

    FROM {{ ref('fact_payments') }}

    GROUP BY 1, 2

),

refunds AS (

    SELECT
        REFUND_DATE_KEY AS DATE_KEY,
        CURRENCY_CODE,

        COUNT(*) AS TOTAL_REFUND_COUNT,

        SUM(CASE WHEN REFUND_STATUS = 'COMPLETED'
            THEN 1 ELSE 0 END)
            AS COMPLETED_REFUND_COUNT,

        SUM(CASE WHEN REFUND_STATUS = 'FAILED'
            THEN 1 ELSE 0 END)
            AS FAILED_REFUND_COUNT,

        SUM(CASE WHEN REFUND_STATUS = 'PENDING'
            THEN 1 ELSE 0 END)
            AS PENDING_REFUND_COUNT,

        SUM(CASE WHEN IS_COMPLETED_REFUND
            AND IS_VALID_REFUND
            THEN 1 ELSE 0 END)
            AS VALIDATED_COMPLETED_REFUND_COUNT,

        SUM(REFUND_AMOUNT)
            AS TOTAL_REFUND_AMOUNT,

        SUM(COMPLETED_REFUND_AMOUNT)
            AS COMPLETED_REFUND_AMOUNT,

        SUM(VALIDATED_COMPLETED_REFUND_AMOUNT)
            AS VALIDATED_COMPLETED_REFUND_AMOUNT

    FROM {{ ref('fact_refunds') }}

    GROUP BY 1, 2

),

expected AS (

    SELECT
        COALESCE(p.DATE_KEY, r.DATE_KEY)
            AS DATE_KEY,

        COALESCE(p.CURRENCY_CODE, r.CURRENCY_CODE)
            AS CURRENCY_CODE,

        COALESCE(p.TOTAL_PAYMENT_COUNT, 0)
            AS TOTAL_PAYMENT_COUNT,

        COALESCE(p.SUCCESSFUL_PAYMENT_COUNT, 0)
            AS SUCCESSFUL_PAYMENT_COUNT,

        COALESCE(p.FAILED_PAYMENT_COUNT, 0)
            AS FAILED_PAYMENT_COUNT,

        COALESCE(p.PENDING_PAYMENT_COUNT, 0)
            AS PENDING_PAYMENT_COUNT,

        COALESCE(p.TOTAL_PAYMENT_AMOUNT, 0)
            AS TOTAL_PAYMENT_AMOUNT,

        COALESCE(p.SUCCESSFUL_PAYMENT_AMOUNT, 0)
            AS SUCCESSFUL_PAYMENT_AMOUNT,

        COALESCE(r.TOTAL_REFUND_COUNT, 0)
            AS TOTAL_REFUND_COUNT,

        COALESCE(r.COMPLETED_REFUND_COUNT, 0)
            AS COMPLETED_REFUND_COUNT,

        COALESCE(r.FAILED_REFUND_COUNT, 0)
            AS FAILED_REFUND_COUNT,

        COALESCE(r.PENDING_REFUND_COUNT, 0)
            AS PENDING_REFUND_COUNT,

        COALESCE(r.VALIDATED_COMPLETED_REFUND_COUNT, 0)
            AS VALIDATED_COMPLETED_REFUND_COUNT,

        COALESCE(r.TOTAL_REFUND_AMOUNT, 0)
            AS TOTAL_REFUND_AMOUNT,

        COALESCE(r.COMPLETED_REFUND_AMOUNT, 0)
            AS COMPLETED_REFUND_AMOUNT,

        COALESCE(r.VALIDATED_COMPLETED_REFUND_AMOUNT, 0)
            AS VALIDATED_COMPLETED_REFUND_AMOUNT

    FROM payments p

    FULL OUTER JOIN refunds r
        ON p.DATE_KEY = r.DATE_KEY
        AND p.CURRENCY_CODE = r.CURRENCY_CODE

),

mart AS (

    SELECT *
    FROM {{ ref('mart_financial_daily') }}

)

SELECT
    COALESCE(e.DATE_KEY, m.DATE_KEY) AS DATE_KEY,

    COALESCE(e.CURRENCY_CODE, m.CURRENCY_CODE)
        AS CURRENCY_CODE,

    e.SUCCESSFUL_PAYMENT_AMOUNT
        AS EXPECTED_PAYMENT_AMOUNT,

    m.SUCCESSFUL_PAYMENT_AMOUNT
        AS ACTUAL_PAYMENT_AMOUNT,

    e.VALIDATED_COMPLETED_REFUND_AMOUNT
        AS EXPECTED_REFUND_AMOUNT,

    m.VALIDATED_COMPLETED_REFUND_AMOUNT
        AS ACTUAL_REFUND_AMOUNT

FROM expected e

FULL OUTER JOIN mart m
    ON e.DATE_KEY = m.DATE_KEY
    AND e.CURRENCY_CODE = m.CURRENCY_CODE

WHERE e.DATE_KEY IS NULL
   OR m.DATE_KEY IS NULL
   OR e.TOTAL_PAYMENT_COUNT IS DISTINCT FROM m.TOTAL_PAYMENT_COUNT
   OR e.SUCCESSFUL_PAYMENT_COUNT IS DISTINCT FROM m.SUCCESSFUL_PAYMENT_COUNT
   OR e.FAILED_PAYMENT_COUNT IS DISTINCT FROM m.FAILED_PAYMENT_COUNT
   OR e.PENDING_PAYMENT_COUNT IS DISTINCT FROM m.PENDING_PAYMENT_COUNT
   OR e.TOTAL_PAYMENT_AMOUNT IS DISTINCT FROM m.TOTAL_PAYMENT_AMOUNT
   OR e.SUCCESSFUL_PAYMENT_AMOUNT IS DISTINCT FROM m.SUCCESSFUL_PAYMENT_AMOUNT
   OR e.TOTAL_REFUND_COUNT IS DISTINCT FROM m.TOTAL_REFUND_COUNT
   OR e.COMPLETED_REFUND_COUNT IS DISTINCT FROM m.COMPLETED_REFUND_COUNT
   OR e.FAILED_REFUND_COUNT IS DISTINCT FROM m.FAILED_REFUND_COUNT
   OR e.PENDING_REFUND_COUNT IS DISTINCT FROM m.PENDING_REFUND_COUNT
   OR e.VALIDATED_COMPLETED_REFUND_COUNT IS DISTINCT FROM m.VALIDATED_COMPLETED_REFUND_COUNT
   OR e.TOTAL_REFUND_AMOUNT IS DISTINCT FROM m.TOTAL_REFUND_AMOUNT
   OR e.COMPLETED_REFUND_AMOUNT IS DISTINCT FROM m.COMPLETED_REFUND_AMOUNT
   OR e.VALIDATED_COMPLETED_REFUND_AMOUNT IS DISTINCT FROM m.VALIDATED_COMPLETED_REFUND_AMOUNT