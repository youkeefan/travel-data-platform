WITH silver AS (

    SELECT
        CURRENCY_CODE,
        UPPER(TRIM(REFUND_STATUS)) AS REFUND_STATUS,
        COUNT(*) AS REFUND_COUNT,
        SUM(REFUND_AMOUNT) AS TOTAL_REFUND_AMOUNT

    FROM {{ ref('stg_refunds') }}

    GROUP BY 1, 2

),

gold AS (

    SELECT
        CURRENCY_CODE,
        REFUND_STATUS,
        COUNT(*) AS REFUND_COUNT,
        SUM(REFUND_AMOUNT) AS TOTAL_REFUND_AMOUNT

    FROM {{ ref('fact_refunds') }}

    GROUP BY 1, 2

)

SELECT
    COALESCE(s.CURRENCY_CODE, g.CURRENCY_CODE)
        AS CURRENCY_CODE,

    COALESCE(s.REFUND_STATUS, g.REFUND_STATUS)
        AS REFUND_STATUS,

    s.REFUND_COUNT AS SILVER_REFUND_COUNT,
    g.REFUND_COUNT AS GOLD_REFUND_COUNT,

    s.TOTAL_REFUND_AMOUNT AS SILVER_REFUND_AMOUNT,
    g.TOTAL_REFUND_AMOUNT AS GOLD_REFUND_AMOUNT,

    g.REFUND_COUNT - s.REFUND_COUNT
        AS COUNT_VARIANCE,

    g.TOTAL_REFUND_AMOUNT - s.TOTAL_REFUND_AMOUNT
        AS AMOUNT_VARIANCE

FROM silver s

FULL OUTER JOIN gold g
    ON s.CURRENCY_CODE = g.CURRENCY_CODE
    AND s.REFUND_STATUS = g.REFUND_STATUS

WHERE s.REFUND_COUNT IS DISTINCT FROM g.REFUND_COUNT
   OR s.TOTAL_REFUND_AMOUNT
        IS DISTINCT FROM g.TOTAL_REFUND_AMOUNT