
WITH source AS (

    SELECT *
    FROM {{ source('travel_bronze', 'booking_items') }}

),

cleaned AS (

    SELECT
        TRIM(BOOKING_ITEM_ID) AS BOOKING_ITEM_ID,
        TRIM(BOOKING_ID) AS BOOKING_ID,

        TRY_TO_TIMESTAMP_NTZ(TRANSACTION_DATE_UTC)
            AS TRANSACTION_DATE_UTC,

        TRY_TO_TIMESTAMP_NTZ(TRANSACTION_DATE_SYD)
            AS TRANSACTION_DATE_SYD,

        TRIM(CATEGORY_BK) AS CATEGORY_BK,
        TRIM(PRODUCT_BK) AS PRODUCT_BK,
        TRIM(VENDOR_BK) AS VENDOR_BK,

        TRY_TO_DECIMAL(GROSS_SALES_AUD, 18, 2)
            AS GROSS_SALES_AUD,

        TRY_TO_DECIMAL(GROSS_MARGIN_AUD, 18, 2)
            AS GROSS_MARGIN_AUD,

        TRY_TO_DECIMAL(DISCOUNT_AUD, 18, 2)
            AS DISCOUNT_AUD,

        TRY_TO_DECIMAL(REFUND_AUD, 18, 2)
            AS REFUND_AUD,

        NULLIF(TRIM(OFFER_BK), '') AS OFFER_BK,
        NULLIF(TRIM(PACKAGE_BK), '') AS PACKAGE_BK,

        TRY_TO_DATE(CHECK_IN_DATE) AS CHECK_IN_DATE,
        TRY_TO_DATE(CHECK_OUT_DATE) AS CHECK_OUT_DATE,

        TRY_TO_NUMBER(ROOM_NIGHTS) AS ROOM_NIGHTS,
        TRY_TO_NUMBER(TRAVELLER_COUNT) AS TRAVELLER_COUNT,

        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT_UTC)
            AS UPDATED_AT_UTC

    FROM source

),

deduplicated AS (

    SELECT *
    FROM cleaned

    WHERE REGEXP_LIKE(BOOKING_ITEM_ID, 'BI[0-9]{7}')
        AND GROSS_SALES_AUD IS NOT NULL

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY BOOKING_ITEM_ID
        ORDER BY UPDATED_AT_UTC DESC NULLS LAST
    ) = 1

)

SELECT *
FROM deduplicated

